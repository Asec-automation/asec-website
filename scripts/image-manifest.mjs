// Regenerates IMAGE_REQUIREMENTS.md from src/config/images.ts and reports which slots are filled.
import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const tmp = path.join(root, '.tmp-images.mjs')
await build({ entryPoints: [path.join(root, 'src/config/images.ts')], outfile: tmp, bundle: true, format: 'esm', platform: 'node', logLevel: 'error' })
const { IMAGE_SLOTS, aspect } = await import(pathToFileURL(tmp).href)
fs.rmSync(tmp)

const filled = (p) => {
  const base = p.replace(/\.[a-z]+$/i, '')
  return ['.avif', '.webp', '.jpg', '.jpeg', '.png', '.svg'].map((e) => base + e).find((f) => fs.existsSync(path.join(root, 'public', f)))
}
const order = { Critical: 0, High: 1, Medium: 2, Low: 3 }
const rows = [...IMAGE_SLOTS].sort((a, b) => order[a.priority] - order[b.priority])
const done = rows.filter((r) => filled(r.path)).length

let md = `# Image Requirements — ASEC Automation website

_Generated by \`npm run images\` from \`src/config/images.ts\`. Do not edit by hand._

**Status: ${done} of ${rows.length} image slots filled.**

## How to add an image
1. Prepare the photo at (or above) the recommended size, in the stated aspect ratio.
2. Save it at the **Expected file path** below, inside the \`public/\` folder
   (e.g. \`public/images/home/home-hero.jpg\`). \`.jpg\`, \`.webp\`, \`.png\` or \`.avif\` all work —
   keep the same base filename.
3. Run \`npm run build\`. The placeholder is replaced automatically; no code changes are needed.
4. Optional: edit the slot's \`alt\` text in \`src/config/images.ts\` to describe the actual photo.

Tips: export JPEG/WebP at ~80% quality; keep heroes under ~400 KB and other images under ~250 KB.
Logos should be transparent PNG or SVG. Only add partner/client logos with written approval.

## Summary

| Status | Image ID | Page | Section | Size | Ratio | Priority | Required |
|---|---|---|---|---|---|---|---|
${rows.map((r) => `| ${filled(r.path) ? '✅' : '⬜'} | \`${r.id}\` | ${r.page} | ${r.section} | ${r.width} × ${r.height} | ${aspect(r.width, r.height)} | ${r.priority} | ${r.required ? 'Required' : 'Optional'} |`).join('\n')}

## Details
`
for (const r of rows) {
  md += `
### ${r.id}
- **Page:** ${r.page}
- **Section:** ${r.section}
- **Description:** ${r.description}
- **Dimensions:** ${r.width} × ${r.height}
- **Aspect ratio:** ${aspect(r.width, r.height)}
- **Suggested filename:** \`${path.basename(r.path)}\`
- **Expected file path:** \`public${r.path}\`
- **Priority:** ${r.priority}
- **Required:** ${r.required ? 'Yes' : 'Optional'}
- **Status:** ${filled(r.path) ? `Filled (\`${filled(r.path)}\`)` : 'Empty — placeholder shown'}
`
}
fs.writeFileSync(path.join(root, 'IMAGE_REQUIREMENTS.md'), md)
console.log(`IMAGE_REQUIREMENTS.md written — ${done}/${rows.length} filled`)
